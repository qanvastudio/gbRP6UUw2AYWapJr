const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const config = require('../seo.config.cjs');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const files = Object.keys(config.pages);
const xml = read('sitemap.xml');
assert(xml.startsWith('<?xml version="1.0" encoding="UTF-8"?>'));
assert(xml.includes('xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"'));
const urls = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(match => match[1]);
assert.equal(new Set(urls).size, files.length, 'Sitemap must have unique URLs');
assert.equal(urls.length, files.length);
const titles = new Set(), descriptions = new Set();
for (const file of files) {
  const html = read(file);
  const expected = config.origin + '/' + (file === 'index.html' ? '' : file);
  const canonical = [...html.matchAll(/<link rel="canonical" href="([^"]+)">/g)];
  assert.equal(canonical.length, 1, `${file}: exactly one canonical required`);
  assert.equal(canonical[0][1], expected);
  assert(urls.includes(expected), `${file}: missing sitemap URL`);
  assert(html.includes('<html lang="es-MX">'));
  assert(!/noindex/i.test(html), `${file}: blocked indexable page`);
  assert(html.includes('name="robots" content="index, follow, max-image-preview:large"'));
  const title = html.match(/<title>([^<]+)<\/title>/)[1];
  const description = html.match(/<meta name="description" content="([^"]+)"/)[1];
  assert(!titles.has(title), `${file}: duplicate title`); titles.add(title);
  assert(!descriptions.has(description), `${file}: duplicate description`); descriptions.add(description);
  assert(title.includes(config.name));
  assert(html.includes(`property="og:url" content="${expected}"`));
  for (const name of ['og:title', 'og:description', 'og:image', 'og:image:alt', 'twitter:card', 'twitter:image']) assert(html.includes(`="${name}"`), `${file}: missing ${name}`);
  const imageUrl = new URL(html.match(/property="og:image" content="([^"]+)"/)[1]);
  assert.equal(imageUrl.origin, config.origin);
  assert(fs.existsSync(path.join(root, decodeURIComponent(imageUrl.pathname.slice(1)))));
  const scripts = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  assert.equal(scripts.length, 1);
  const schema = JSON.parse(scripts[0][1]);
  assert.equal(schema['@context'], 'https://schema.org');
  const graph = schema['@graph'];
  const ids = new Set(graph.map(node => node['@id']));
  assert.equal(ids.size, graph.length);
  const person = graph.find(node => node['@type'] === 'Person');
  assert.equal(person.name, config.name);
  assert.equal(person.telephone, '+525579468246');
  function references(value) {
    if (!value || typeof value !== 'object') return;
    if (Object.keys(value).length === 1 && value['@id']) assert(ids.has(value['@id']), `${file}: unresolved JSON-LD reference`);
    Object.values(value).forEach(references);
  }
  references(graph);
  if (file.startsWith('articulo-')) assert(graph.some(node => node['@type'] === 'Article'));
  if (file !== 'index.html') assert(graph.some(node => node['@type'] === 'BreadcrumbList'));
  assert(!/aggregateRating|reviewRating|datePublished|dateModified|hasCredential/.test(scripts[0][1]), 'Do not invent reviews, editorial dates or credential identifiers');
}
const pages = fs.readdirSync(root).filter(file => file.endsWith('.html') && file !== '404.html');
assert.deepEqual([...pages].sort(), [...files].sort(), 'Every indexable page must be registered');
assert(!urls.some(url => /404|index\.html|#/.test(url)));
assert(read('404.html').includes('content="noindex, follow"'));
assert(read('robots.txt').includes(`Sitemap: ${config.origin}/sitemap.xml`));
assert(!/^Disallow:\s*\/$/m.test(read('robots.txt')));
assert.equal(read('CNAME').trim(), new URL(config.origin).hostname);
assert(fs.existsSync(path.join(root, '.nojekyll')));
assert.equal((read('trayectoria.html').match(/<li><h2>/g) || []).length, 26, 'Trajectory must be readable without JavaScript');
const { siteFiles } = require('./site-files.cjs');
for (const file of ['sitemap.xml', 'robots.txt', 'CNAME', '.nojekyll', '404.html']) assert(siteFiles().includes(file), `${file}: missing from production package`);
console.log(`PASS SEO: ${files.length} canonical URLs, unique metadata, social previews, JSON-LD references, crawl controls and static trajectory.`);
